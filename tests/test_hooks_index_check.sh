#!/usr/bin/env bash
# Regression suite for the PostToolUse index hook (hooks/index_check.py, OPERATING-MODEL §9).
# Run: bash tests/test_hooks_index_check.sh   Exits non-zero on any failure.
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
HOOK="$ROOT/hooks/index_check.py"

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '  ok   %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  FAIL %s\n' "$1"; }

# run <file_path> [tool] : the hook's stdout for a Write/Edit of that path
run() {
  python3 -c 'import json,sys; print(json.dumps({"hook_event_name":"PostToolUse","tool_name":sys.argv[2],"tool_input":{"file_path":sys.argv[1]},"cwd":sys.argv[3]}))' \
    "$1" "${2:-Write}" "$TMP" | python3 "$HOOK"
}
# ctx <file_path> : the additionalContext, or "" when the hook printed {}
ctx() {
  run "$@" | python3 -c '
import json, sys
d = json.load(sys.stdin)
if d:
    h = d["hookSpecificOutput"]
    assert h["hookEventName"] == "PostToolUse", h
    print(h["additionalContext"])'
}
silent() { local got; got="$(ctx "$2")"; [ -z "$got" ] && ok "$1" || bad "$1 (got: $got)"; }
warns()  { local got; got="$(ctx "$2")"; printf '%s' "$got" | grep -q -- "$3" && ok "$1" || bad "$1 (want /$3/, got: $got)"; }

# long_doc <path> [first line] [contents?] : 4 sections, > 150 lines
long_doc() {
  { echo "${2:-# Report}"; echo; echo "Summary."; echo
    [ "${3:-}" = contents ] && printf '## Contents\n\n| § | answers |\n|---|---|\n\n'
    for s in 1 2 3 4; do echo "## Section $s"; for i in $(seq 1 40); do echo "line $i"; done; done
  } > "$1"
}

echo "--- Contents table (check a)"
mkdir -p "$TMP/a"
long_doc "$TMP/a/long.md"
warns  "long file without Contents warns"          "$TMP/a/long.md" "no \`## Contents\` table"
warns  "warning names the rule"                    "$TMP/a/long.md" "OPERATING-MODEL §9"
long_doc "$TMP/a/long.md" "# Report" contents
silent "long file with Contents is silent"         "$TMP/a/long.md"
printf '# Short\n\n## A\n## B\n## C\n## D\n' > "$TMP/a/long.md"
silent "short file is silent"                      "$TMP/a/long.md"
fence="$TMP/a/long.md"
{ echo "# Fenced"; echo '```'; for s in 1 2 3 4 5; do echo "## not a section $s"; done; echo '```'
  for i in $(seq 1 160); do echo "x"; done; } > "$fence"
silent "headings inside a code fence do not count" "$fence"

mkdir -p "$TMP/skill"
long_doc "$TMP/skill/SKILL.md"
silent "SKILL.md is silent"                        "$TMP/skill/SKILL.md"
mkdir -p "$TMP/gen"
long_doc "$TMP/gen/out.md" "<!-- generated by a tool; never edit by hand -->"
silent "generated marker in the first lines is silent" "$TMP/gen/out.md"
mkdir -p "$TMP/node_modules/pkg"
long_doc "$TMP/node_modules/pkg/doc.md"
silent "anything under node_modules is silent"     "$TMP/node_modules/pkg/doc.md"

echo "--- folder INDEX.md (checks b, c)"
mkdir -p "$TMP/b"
printf '# One\n' > "$TMP/b/one.md"
silent "first .md in a folder is silent"           "$TMP/b/one.md"
printf '# Two\n' > "$TMP/b/two.md"
warns  "second .md without INDEX.md warns"         "$TMP/b/two.md" "no INDEX.md"
printf '# Index\n\n| file | answers |\n|---|---|\n| [one.md](one.md) | x |\n' > "$TMP/b/INDEX.md"
warns  "INDEX.md missing this file warns"          "$TMP/b/two.md" "does not mention two.md"
silent "INDEX.md listing this file is silent"      "$TMP/b/one.md"
silent "editing INDEX.md itself is silent"         "$TMP/b/INDEX.md"
mkdir -p "$TMP/repo"
printf '# Readme\n' > "$TMP/repo/README.md"; printf '# Notes\n' > "$TMP/repo/notes.md"
silent "README.md does not count towards a folder's documents" "$TMP/repo/notes.md"

echo "--- inputs"
printf 'x\n' > "$TMP/b/code.py"; printf 'y\n' > "$TMP/b/more.py"
silent "non-.md file is silent"                    "$TMP/b/code.py"
silent "missing file is silent"                    "$TMP/b/nope.md"
mkdir -p "$TMP/rel"; long_doc "$TMP/rel/r.md"
warns  "relative path resolves against payload cwd" "rel/r.md" "no \`## Contents\` table"
for input in 'garbage' '' '[]' '{"tool_input": null}' '{"tool_input": {"file_path": 7}}'; do
  out="$(printf '%s' "$input" | python3 "$HOOK" 2>&1)"; rc=$?
  [ "$rc" -eq 0 ] && [ "$out" = "{}" ] && ok "malformed stdin ($input) -> {} exit 0" \
    || bad "malformed stdin ($input) -> rc=$rc out=$out"
done
before="$(cd "$TMP" && find . | sort)"; run "$TMP/b/two.md" >/dev/null
[ "$before" = "$(cd "$TMP" && find . | sort)" ] && ok "the hook writes nothing" || bad "the hook wrote a file"
grep -qE '^import.*subprocess|os\.system|os\.popen|write_text|open\([^)]*["'"'"'][wa]' "$HOOK" \
  && bad "hook must not spawn processes or open files for writing" \
  || ok "no subprocess, no write mode in the hook"

echo "--- registration"
python3 - "$ROOT/hooks/hooks.json" <<'PY' && ok "PostToolUse Write|Edit|MultiEdit registered via CLAUDE_PLUGIN_ROOT" || bad "hook registration"
import json, sys
groups = json.load(open(sys.argv[1]))["hooks"]["PostToolUse"]
hit = [g for g in groups for x in g["hooks"]
       if "${CLAUDE_PLUGIN_ROOT}/hooks/index_check.py" in x["command"]]
assert hit, groups
assert set(hit[0]["matcher"].split("|")) == {"Write", "Edit", "MultiEdit"}, hit[0]["matcher"]
PY

echo
echo "hooks-index-check: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
